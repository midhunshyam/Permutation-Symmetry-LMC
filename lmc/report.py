"""Helpers shared by the analysis scripts: reading results and writing Markdown tables."""

from __future__ import annotations

import json
import math
from pathlib import Path

from lmc.stats import mean_sem


def load_jsonl(path: Path) -> list[dict]:
    if not path.exists():
        return []
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def fmt_p(p) -> str:
    """Format a p- or q-value."""
    if p is None or math.isnan(p):
        return "–"
    return f"{p:.3f}" if p >= 0.001 else "<0.001"


def p_clause(p, name="p") -> str:
    """'p = 0.012' or 'p < 0.001'."""
    text = fmt_p(p)
    return f"{name} < 0.001" if text == "<0.001" else f"{name} = {text}"


def fmt_float(x, digits=3) -> str:
    return "–" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{x:.{digits}f}"


def fmt_mean_sem(values, digits=4, percent=False) -> str:
    """'mean ± SEM'; with percent=True, values are fractions printed as percentages.
    Values with |mean| >= 100 are printed as integers with thousands separators."""
    m, s = mean_sem(values)
    if math.isnan(m):
        return "–"
    if percent:
        return f"{100 * m:.2f} ± {100 * s:.2f}"
    if abs(m) >= 100:
        return f"{m:,.0f} ± {s:,.0f}"
    return f"{m:.{digits}f} ± {s:.{digits}f}"


def fmt_diff(test, digits=3, scale=1.0) -> str:
    """'+mean ± SEM' of a TTestResult's difference."""
    return f"{scale * test.mean_diff:+.{digits}f} ± {scale * test.sem:.{digits}f}"


class Report:
    """Accumulates Markdown lines and writes them to one file."""

    def __init__(self, title: str, source: str):
        self.lines = [f"# {title}", "",
                      f"Generated by `{source}` from the result files. Do not edit by hand.", ""]

    def add(self, text: str = ""):
        self.lines.append(text)

    def paragraph(self, text: str):
        self.lines += [text, ""]

    def heading(self, text: str, level: int = 2):
        self.lines += ["#" * level + " " + text, ""]

    def table(self, header, rows, text_columns=1):
        """Markdown table; the first `text_columns` columns are left-aligned, the rest right-aligned."""
        self.add("| " + " | ".join(header) + " |")
        self.add("|" + "|".join("---" if i < text_columns else "---:" for i in range(len(header))) + "|")
        for row in rows:
            self.add("| " + " | ".join(str(c) for c in row) + " |")
        self.add()

    def write(self, path: Path):
        path.write_text("\n".join(self.lines))
        print(f"wrote {path}")
